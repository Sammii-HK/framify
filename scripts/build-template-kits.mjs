#!/usr/bin/env node
/**
 * Build the sellable template kits in /template-kits into:
 *
 *   1. lib/template-kits.generated.ts  the kit files as strings, so the
 *      download route can zip them on any runtime (Vercel, Cloudflare)
 *      without filesystem access.
 *   2. public/demos/<slug>/            a live demo of each kit (noindex,
 *      with a small "Buy this template" bar). README and licence stay
 *      in the paid download only.
 *
 * Run after editing anything in /template-kits:
 *   node scripts/build-template-kits.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const kitsDir = path.join(root, 'template-kits')
const TEXT = new Set(['.html', '.css', '.js', '.md', '.svg', '.txt', '.json'])
const DEMO_EXCLUDE = new Set(['README.md', 'LICENSE.md'])

// Kit slug -> gallery template type (must match lib/template-data.ts)
const KIT_TO_TYPE = {
  'haven-therapist': 'therapist',
  'launchpad-app': 'app-launch',
  'spotless-cleaning': 'cleaning',
}

function walk(dir, base = dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) return entry.name === 'screenshots' ? [] : walk(full, base)
    if (!TEXT.has(path.extname(entry.name))) return []
    return [path.relative(base, full).split(path.sep).join('/')]
  })
}

function demoBar(slug, type) {
  const name = slug.split('-')[0].replace(/^./, (c) => c.toUpperCase())
  return `
<!-- CraftMyPage demo bar (not part of the template) -->
<a href="https://craftmypage.com/templates/${type}" style="position:fixed;right:16px;bottom:16px;z-index:9999;display:inline-flex;align-items:center;gap:10px;padding:10px 16px;border-radius:999px;background:#111;color:#fff;font:600 14px/1.2 system-ui,-apple-system,'Segoe UI',sans-serif;text-decoration:none;box-shadow:0 10px 30px -10px rgba(0,0,0,.5)">
  <span style="opacity:.7;font-weight:500">Demo</span> ${name} template on CraftMyPage <span aria-hidden="true">&rarr;</span>
</a>
`
}

function toDemo(file, content, slug, type) {
  if (!file.endsWith('.html')) return content
  return content
    .replace(/[ \t]*<!-- EDIT: (set this to )?your (real|live) address[^>]*-->[ \t]*\n/gi, '')
    .replace(/[ \t]*<link rel="canonical"[^>]*>[ \t]*\n/i, '')
    .replace(/[ \t]*<meta name="robots"[^>]*>[ \t]*\n/i, '')
    .replace(/<head>/i, '<head>\n  <meta name="robots" content="noindex, follow" />')
    .replace(/<\/body>/i, `${demoBar(slug, type)}</body>`)
}

const kits = fs.readdirSync(kitsDir, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort()
const generated = {}

for (const slug of kits) {
  const type = KIT_TO_TYPE[slug]
  if (!type) throw new Error(`No gallery type mapped for kit "${slug}". Add it to KIT_TO_TYPE.`)
  const files = walk(path.join(kitsDir, slug)).sort()
  generated[slug] = files.map((file) => ({ path: file, content: fs.readFileSync(path.join(kitsDir, slug, file), 'utf8') }))

  const demoDir = path.join(root, 'public', 'demos', slug)
  fs.rmSync(demoDir, { recursive: true, force: true })
  for (const { path: file, content } of generated[slug]) {
    if (DEMO_EXCLUDE.has(file)) continue
    const out = path.join(demoDir, file)
    fs.mkdirSync(path.dirname(out), { recursive: true })
    fs.writeFileSync(out, toDemo(file, content, slug, type))
  }
  console.log(`  ${slug}: ${files.length} files, demo -> public/demos/${slug}/`)
}

const ts = `// AUTO-GENERATED by scripts/build-template-kits.mjs from /template-kits. Do not edit by hand.
/* eslint-disable */

export interface TemplateKitFile {
  path: string
  content: string
}

export const templateKitFiles: Record<string, TemplateKitFile[]> = ${JSON.stringify(generated, null, 2)}
`
fs.writeFileSync(path.join(root, 'lib', 'template-kits.generated.ts'), ts)
console.log(`  wrote lib/template-kits.generated.ts (${(Buffer.byteLength(ts) / 1024).toFixed(0)} KB)`)
